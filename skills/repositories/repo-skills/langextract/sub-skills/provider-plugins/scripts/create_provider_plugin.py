"""Generate a self-contained LangExtract provider plugin package.

The generator is safe by default: it writes a package scaffold under the current
working directory or --output-dir and does not install packages, call model APIs,
or depend on the original LangExtract source checkout. Use --install-and-test
only in a throwaway environment where mutating installed packages is acceptable.
"""


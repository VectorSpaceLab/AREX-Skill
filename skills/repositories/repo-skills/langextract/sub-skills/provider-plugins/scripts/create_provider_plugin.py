def _provider_base_name(raw: str) -> str:
    words = re.findall(r"[A-Za-z0-9]+", raw)
    if not words:
        raise ValueError("provider_name must contain at least one letter or digit")
    base = "".join(word[:1].upper() + word[1:] for word in words)
    if not base[0].isalpha():
        base = "Provider" + base
    return base


def _default_suffix(provider_base: str) -> str:
    suffix = re.sub(r"[^A-Za-z0-9]+", "", provider_base).lower()
    if suffix.endswith("languagemodel"):
        suffix = suffix[: -len("languagemodel")]
    return suffix or "provider"


def _normalize_suffix(raw: str) -> str:
    suffix = re.sub(r"[^A-Za-z0-9]+", "-", raw).strip("-").lower()
    if not suffix:
        raise ValueError("package name must contain at least one letter or digit")
    if not re.match(r"^[a-z0-9](?:[a-z0-9-]*[a-z0-9])?$", suffix):
        raise ValueError("package name must start and end with a letter or digit")
    return suffix


def _validate_patterns(patterns: list[str]) -> None:
    for pattern in patterns:
        try:
            re.compile(pattern)
        except re.error as exc:
            raise ValueError(f"invalid regex pattern {pattern!r}: {exc}") from exc


def _quote_patterns(patterns: list[str]) -> str:
    return ", ".join(repr(pattern) for pattern in patterns)


def _write_file(path: Path, content: str, *, force: bool) -> None:
    if path.exists() and not force:
        raise FileExistsError(f"{path} already exists; use --force to overwrite")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")


def _schema_blocks(module_name: str, provider_base: str, class_name: str, with_schema: bool) -> tuple[str, str, str, str, str]:
    schema_class = f"{provider_base}Schema"
    if not with_schema:
        return "", "", "", "", ""
    schema_import = f"from {module_name}.schema import {schema_class}"
    schema_init = textwrap.indent(
        'self.response_schema = kwargs.get("response_schema")\n'
        'self.structured_output = bool(kwargs.get("structured_output", False))',
        "        ",
    )
    schema_methods = textwrap.indent(
        f'''\
@classmethod
def get_schema_class(cls):
    """Return this provider's schema adapter."""
    return {schema_class}

def apply_schema(self, schema_instance):
    """Apply or clear schema configuration."""
    super().apply_schema(schema_instance)
    if schema_instance is None:
        self.response_schema = None
        self.structured_output = False
        return
    config = schema_instance.to_provider_config()
    self.response_schema = config.get("response_schema")
    self.structured_output = bool(config.get("structured_output", False))
''',
        "    ",
    )
    schema_runtime = textwrap.indent(
        'if self.response_schema and self.structured_output:\n'
        '    effective_kwargs = {**effective_kwargs, "response_schema": self.response_schema}',
        "            ",
    )
    schema_test = textwrap.indent(
        f'''\
examples = [
    data.ExampleData(
        text="Alice founded ExampleCo.",
        extractions=[
            data.Extraction(
                extraction_class="person",
                extraction_text="Alice",
                attributes={{"role": "founder"}},
            )
        ],
    )
]
schema_model = factory.create_model(
    factory.ModelConfig(model_id=model_id, provider=PROVIDER_CLASS_NAME),
    examples=examples,
    use_schema_constraints=True,
)
assert schema_model.schema is not None
assert schema_model.requires_fence_output is False
schema_outputs = list(schema_model.infer(["Alice founded ExampleCo."]))
assert schema_outputs[0][0].output == '{{"extractions": []}}'
schema_model.apply_schema(None)
assert schema_model.schema is None
print("OK: schema lifecycle")
''',
        "    ",
    )
    return schema_import, schema_init, schema_methods, schema_runtime, schema_test


def _create_files(args: argparse.Namespace) -> Path:
    provider_base = _provider_base_name(args.provider_name)
    class_name = provider_base if provider_base.endswith("LanguageModel") else f"{provider_base}LanguageModel"
    provider_display = class_name.removesuffix("LanguageModel")
    suffix = _normalize_suffix(args.package_name or _default_suffix(provider_base))
    distribution_name = f"langextract-{suffix}"
    module_name = f"langextract_{suffix.replace('-', '_')}"
    entry_point = suffix.replace("-", "_")
    env_var = re.sub(r"[^A-Z0-9]+", "_", suffix.upper()).strip("_") + "_API_KEY"
    patterns = args.patterns or [f"^{suffix}"]
    _validate_patterns(patterns)
    default_model_id = re.sub(r"^\^", "", patterns[0]) or suffix
    default_model_id = re.match(r"[A-Za-z0-9._:/-]+", default_model_id).group(0) if re.match(r"[A-Za-z0-9._:/-]+", default_model_id) else suffix

    output_root = Path(args.output_dir or ".").expanduser()
    base_dir = output_root / distribution_name
    if base_dir.exists() and not base_dir.is_dir():
        raise FileExistsError(f"target exists and is not a directory: {base_dir}")
    if base_dir.exists() and any(base_dir.iterdir()) and not args.force:
        raise FileExistsError(
            f"target directory is not empty: {base_dir}. Use --force to overwrite generated files."
        )

    schema_import, schema_init, schema_methods, schema_runtime, schema_test = _schema_blocks(
        module_name, provider_display, class_name, args.with_schema
    )

    patterns_markdown = "\n".join(f"- `{pattern}`" for pattern in patterns)
    substitutions = {
        "provider_display": provider_display,
        "class_name": class_name,
        "schema_class": f"{provider_display}Schema",
        "module_name": module_name,
        "entry_point": entry_point,
        "distribution_name": distribution_name,
        "patterns_literal": _quote_patterns(patterns),
        "patterns_list": repr(patterns),
        "patterns_markdown": patterns_markdown,
        "priority": str(args.priority),
        "env_var": env_var,
        "default_model_id": default_model_id,
        "schema_import": schema_import,
        "schema_init": schema_init,
        "schema_methods": schema_methods,
        "schema_runtime": schema_runtime,
        "schema_test": schema_test,
    }

    files: dict[Path, str] = {
        base_dir / "pyproject.toml": _PYPROJECT_TEMPLATE.substitute(substitutions),
        base_dir / "README.md": _README_TEMPLATE.substitute(substitutions),
        base_dir / "LICENSE": _LICENSE,
        base_dir / ".gitignore": _GITIGNORE,
        base_dir / _MARKER: "Generated by LangExtract provider plugin generator.\n",
        base_dir / module_name / "__init__.py": _INIT_TEMPLATE.substitute(substitutions),
        base_dir / module_name / "provider.py": _PROVIDER_TEMPLATE.substitute(substitutions),
        base_dir / "test_plugin.py": _TEST_TEMPLATE.substitute(substitutions),
    }
    if args.with_schema:
        files[base_dir / module_name / "schema.py"] = _SCHEMA_TEMPLATE.substitute(substitutions)

    for path, content in files.items():
        _write_file(path, content, force=args.force)
    return base_dir


def _install_and_test(base_dir: Path, *, install_deps: bool) -> None:
    env = os.environ.copy()
    env.setdefault("PIP_NO_INPUT", "1")
    env.setdefault("PIP_DISABLE_PIP_VERSION_CHECK", "1")
    install_cmd = [sys.executable, "-m", "pip", "install", "-e", str(base_dir)]
    if not install_deps:
        install_cmd.append("--no-deps")
    subprocess.run(install_cmd, check=True, env=env)
    subprocess.run([sys.executable, str(base_dir / "test_plugin.py")], check=True, env=env)


def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Create a self-contained LangExtract provider plugin scaffold.",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog=textwrap.dedent(
            """
            Examples:
              python create_provider_plugin.py MyProvider
              python create_provider_plugin.py MyProvider --with-schema --patterns '^my-model' '^myprovider/'
              python create_provider_plugin.py MyProvider --output-dir ./plugins --package-name myprovider
              python create_provider_plugin.py MyProvider --install-and-test --no-input
            """
        ),
    )
    parser.add_argument("provider_name", help="Provider display/class stem, e.g. MyProvider")
    parser.add_argument("--patterns", nargs="+", help="Regex model-ID patterns; default is based on package name")
    parser.add_argument("--package-name", help="Distribution suffix after 'langextract-', e.g. myprovider")
    parser.add_argument("--output-dir", help="Directory in which to create the plugin package; default: current directory")
    parser.add_argument("--priority", type=int, default=10, help="router.register priority; built-ins use 10")
    parser.add_argument("--with-schema", action="store_true", help="Generate a BaseSchema adapter and schema smoke checks")
    parser.add_argument("--force", action="store_true", help="Overwrite predictable generated files if the target exists")
    parser.add_argument("--install-and-test", action="store_true", help="After generation, run pip install -e and test_plugin.py")
    parser.add_argument("--install-deps", action="store_true", help="With --install-and-test, allow pip to install dependencies instead of --no-deps")
    parser.add_argument("--no-input", action="store_true", help="Accepted for scripted usage; the generator never prompts")
    return parser.parse_args(argv)


def main(argv: list[str] | None = None) -> int:
    args = parse_args(argv)
    try:
        base_dir = _create_files(args)
    except (FileExistsError, ValueError) as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 2

    print(f"Created LangExtract provider plugin scaffold: {base_dir}")
    print("Next steps:")
    print(f"  1. Edit {base_dir / 'pyproject.toml'} and provider SDK dependencies.")
    print("  2. Replace mock inference in the generated package module's provider.py with backend calls.")
    print(f"  3. Run: python {base_dir / 'test_plugin.py'}")
    print("  4. In a throwaway environment, install with: python -m pip install -e <plugin-dir>")

    if args.install_and_test:
        try:
            _install_and_test(base_dir, install_deps=args.install_deps)
        except subprocess.CalledProcessError as exc:
            print(f"ERROR: install/test command failed with exit code {exc.returncode}", file=sys.stderr)
            return exc.returncode or 1
        print("Install and non-live smoke test succeeded.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

#!/usr/bin/env python3
"""Render TensorFlowOnSpark Spark ML pipeline skeletons.

This helper only writes code templates. It never trains a model, loads a SavedModel, or submits Spark jobs.
"""

from __future__ import annotations

import argparse
from pathlib import Path
from textwrap import dedent

PLACEHOLDER_INPUT = [("<df_column>", "<input_tensor>")]
PLACEHOLDER_OUTPUT = [("<output_tensor>", "<df_column>")]


def parse_mapping_entries(items, *, mode):
    mapping = []
    seen = set()
    for raw in items:
        if ":" not in raw:
            raise ValueError(f"{mode} mappings must use COL:TENSOR syntax")
        left, right = (part.strip() for part in raw.split(":", 1))
        if not left or not right:
            raise ValueError(f"{mode} mappings must use non-empty COL:TENSOR pairs")
        if left in seen:
            raise ValueError(f"duplicate {mode} mapping key: {left}")
        seen.add(left)
        mapping.append((left, right))
    return sorted(mapping)


def render_mapping_constant(name, mapping, placeholder):
    rows = mapping if mapping else placeholder
    body = "\n".join(f"    {left!r}: {right!r}," for left, right in rows)
    return f"{name} = {{\n{body}\n}}"



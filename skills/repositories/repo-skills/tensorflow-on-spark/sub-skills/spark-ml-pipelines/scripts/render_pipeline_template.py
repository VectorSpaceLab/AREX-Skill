def render(mode, input_mapping, output_mapping):
    parts = [render_header(), "# Input mapping keys are Spark DataFrame columns; values are TensorFlow input tensors."]
    parts.append(render_mapping_constant("INPUT_MAPPING", input_mapping, PLACEHOLDER_INPUT))

    if mode in {"train", "both"}:
        parts.append(TRAIN_BLOCK)

    if mode in {"inference", "both"}:
        parts.append("# Output mapping keys are TensorFlow output tensors; values are Spark DataFrame columns.")
        parts.append(render_mapping_constant("OUTPUT_MAPPING", output_mapping, PLACEHOLDER_OUTPUT))
        parts.append(INFERENCE_BLOCK)

    return "\n\n".join(parts).rstrip() + "\n"


def build_arg_parser():
    parser = argparse.ArgumentParser(description="Render a TensorFlowOnSpark Spark ML pipeline skeleton.")
    parser.add_argument("--mode", choices=["train", "inference", "both"], default="both", help="Which skeleton sections to render.")
    parser.add_argument("--input-mapping", action="append", default=[], metavar="DF_COL:TENSOR", help="Input mapping entry for the rendered skeleton.")
    parser.add_argument("--output-mapping", action="append", default=[], metavar="TENSOR:DF_COL", help="Output mapping entry for the rendered skeleton.")
    parser.add_argument("--output", default="-", help="Write the rendered skeleton to this path, or '-' for stdout.")
    return parser


def main(argv=None):
    parser = build_arg_parser()
    args = parser.parse_args(argv)
    input_mapping = parse_mapping_entries(args.input_mapping, mode="input")
    output_mapping = parse_mapping_entries(args.output_mapping, mode="output")
    rendered = render(args.mode, input_mapping, output_mapping)
    if args.output == "-":
        print(rendered, end="")
    else:
        path = Path(args.output)
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(rendered, encoding="utf-8")


if __name__ == "__main__":
    main()

#!/usr/bin/env python3
import argparse
import importlib.util
import json
import pathlib
import time


def load_module(path, name):
    spec = importlib.util.spec_from_file_location(name, path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def patch(value, channel_shift=0.0):
    return [
        [[value, value + 0.05], [value + 0.10, value + 0.15]],
        [[value + channel_shift, value + 0.05 + channel_shift], [value + 0.10 + channel_shift, value + 0.15 + channel_shift]],
        [[value - channel_shift, value + 0.05 - channel_shift], [value + 0.10 - channel_shift, value + 0.15 - channel_shift]],
    ]


def invert(image):
    return [[[-pixel for pixel in row] for row in channel] for channel in image]


def add_delta(image, delta):
    return [[[max(-1.0, min(1.0, pixel + delta)) for pixel in row] for row in channel] for channel in image]


def make_triplets():
    triplets = []
    bases = [(-0.8, 0.00), (-0.5, 0.02), (-0.2, -0.02), (0.1, 0.03), (0.35, -0.03), (0.6, 0.01)]
    for index, (value, shift) in enumerate(bases):
        ref = patch(value, shift)
        mild = add_delta(ref, 0.02 if index % 2 == 0 else -0.02)
        severe = invert(ref) if index % 3 == 0 else add_delta(ref, 0.65 if value < 0 else -0.65)
        if index % 2 == 0:
            p0, p1, judge = mild, severe, 0
        else:
            p0, p1, judge = severe, mild, 1
        triplets.append({"id": f"synthetic_{index}", "ref": ref, "p0": p0, "p1": p1, "judge": judge})
    return triplets


def run_recovery(attempt_dir, skills_root):
    attempt_dir = pathlib.Path(attempt_dir)
    skills_root = pathlib.Path(skills_root)
    recovery_dir = attempt_dir / "recovery"
    logs_dir = recovery_dir / "logs"
    logs_dir.mkdir(parents=True, exist_ok=True)

    module_plan_path = attempt_dir / "module_plan.json"
    handoff_path = attempt_dir / "environment" / "runtime_handoff.json"
    with module_plan_path.open("r", encoding="utf-8") as handle:
        module_plan = json.load(handle)
    with handoff_path.open("r", encoding="utf-8") as handle:
        handoff = json.load(handle)

    distance_module = load_module(skills_root / "lpips_feature_distance" / "scripts" / "lpips_distance.py", "lpips_distance")
    calibration_module = load_module(skills_root / "linear_calibration_ranking" / "scripts" / "calibrate_ranking.py", "calibrate_ranking")
    protocol_module = load_module(skills_root / "bapps_2afc_protocol" / "scripts" / "evaluate_2afc.py", "evaluate_2afc")

    start = time.time()
    triplets = make_triplets()
    distance_records = []
    calibration_items = []
    for item in triplets:
        d0 = distance_module.lpips_distance(item["ref"], item["p0"])
        d1 = distance_module.lpips_distance(item["ref"], item["p1"])
        layers0 = [entry["raw_distance"] for entry in d0["layer_contributions"]]
        layers1 = [entry["raw_distance"] for entry in d1["layer_contributions"]]
        distance_records.append({"id": item["id"], "d0_uncalibrated": d0["distance"], "d1_uncalibrated": d1["distance"], "judge": item["judge"], "layers0": layers0, "layers1": layers1})
        calibration_items.append({"id": item["id"], "layers0": layers0, "layers1": layers1, "judge": item["judge"]})

    calibration = calibration_module.calibrate(calibration_items, initial_weights=[1.0, 1.0, 1.0], steps=20, learning_rate=0.2)
    weights = calibration["params_after"]
    scored_items = []
    for record in distance_records:
        d0 = calibration_module.score_layers(record["layers0"], weights)
        d1 = calibration_module.score_layers(record["layers1"], weights)
        scored_items.append({"id": record["id"], "d0": d0, "d1": d1, "judge": record["judge"]})
    evaluation = protocol_module.evaluate_precomputed(scored_items)

    generated_data_item = {"dataset": "synthetic_bapps_style_2afc", "split": "bounded_proxy_6_triplets", "sample_count": len(triplets), "items": [{"id": item["id"], "judge": item["judge"], "source": "deterministic synthetic patch generated by recovery harness"} for item in triplets], "resource_file_provenance": "not applicable: paper-specific BAPPS download is large and unavailable; proxy is declared synthetic"}
    training_trace = {"optimizer_step_executed": calibration["optimizer_step_executed"], "reduced_training_executed": True, "params_before": calibration["params_before"], "params_after": calibration["params_after"], "loss_before": calibration["before"]["loss"], "loss_after": calibration["after"]["loss"], "accuracy_before": calibration["before"]["accuracy"], "accuracy_after": calibration["after"]["accuracy"], "history": calibration["history"]}

    (logs_dir / "generated_data_item.json").write_text(json.dumps(generated_data_item, indent=2), encoding="utf-8")
    (logs_dir / "training_trace.json").write_text(json.dumps(training_trace, indent=2), encoding="utf-8")
    (logs_dir / "distance_records.json").write_text(json.dumps(distance_records, indent=2), encoding="utf-8")
    (logs_dir / "evaluation_records.json").write_text(json.dumps(evaluation, indent=2), encoding="utf-8")

    invocations = {
        "schema_version": 1,
        "generated_skills_root": str(skills_root),
        "invocations": [
            {"module": "lpips_feature_distance", "skill": "lpips_feature_distance", "evidence": "imported helper", "kind": "imported helper", "artifact": "recovery/logs/distance_records.json"},
            {"module": "linear_calibration_ranking", "skill": "linear_calibration_ranking", "evidence": "imported helper", "kind": "imported helper", "artifact": "recovery/logs/training_trace.json"},
            {"module": "bapps_2afc_protocol", "skill": "bapps_2afc_protocol", "evidence": "imported helper", "kind": "imported helper", "artifact": "recovery/logs/evaluation_records.json"},
            {"module": "lpips_recovery_harness", "skill": "lpips_recovery_harness", "evidence": "called script", "kind": "called script", "artifact": "recovery/recovery_result.json"},
        ],
    }
    (logs_dir / "generated_skill_invocations.json").write_text(json.dumps(invocations, indent=2), encoding="utf-8")

    source_manifest = {
        "schema_version": 1,
        "allowed_sources_used": [
            str(attempt_dir / "paper_profile.md"),
            str(module_plan_path),
            str(attempt_dir / "modules"),
            str(skills_root),
            str(handoff_path),
        ],
        "runtime_handoff": str(handoff_path),
        "original_repo_used": False,
        "original_repo_paths": [],
        "notes": "Recovery uses generated skills and attempt artifacts only; original implementation repository is excluded.",
    }
    (recovery_dir / "source_manifest.json").write_text(json.dumps(source_manifest, indent=2), encoding="utf-8")

    command_log = {
        "schema_version": 1,
        "commands": [
            {
                "command": "python scripts/run_lpips_recovery.py --attempt-dir <attempt_dir> --skills-root <generated_skills_root>",
                "label": "lpips_proxy_recovery",
                "status": "completed",
                "returncode": 0,
                "elapsed_seconds": round(time.time() - start, 4),
                "stdout_tail": "recovery_result.json written",
                "stderr_tail": "",
            }
        ],
    }
    (logs_dir / "experiment_command_log.json").write_text(json.dumps(command_log, indent=2), encoding="utf-8")

    target = module_plan["fast_recovery_target"]
    result = {
        "schema_version": 1,
        "paper_id": module_plan["paper_id"],
        "experiment": target["dataset"],
        "is_proxy": True,
        "sample_count": evaluation["sample_count"],
        "metrics": {"2afc_accuracy": evaluation["accuracy"], "proxy_threshold": 0.8},
        "paper_target": target,
        "commands": ["python scripts/run_lpips_recovery.py --attempt-dir <attempt_dir> --skills-root <generated_skills_root>"],
        "artifacts": [
            "recovery/logs/generated_data_item.json",
            "recovery/logs/training_trace.json",
            "recovery/logs/distance_records.json",
            "recovery/logs/evaluation_records.json",
            "recovery/logs/generated_skill_invocations.json",
        ],
        "mechanism_checks": {
            "proxy_declared": True,
            "soft_mode_proxy_allowed": True,
            "full_bapps_blocked": not handoff.get("runtime_ready", False),
            "normalized_inputs_used": True,
            "multi_layer_feature_distance_executed": True,
            "layerwise_squared_differences_logged": True,
            "nonnegative_calibration_weights": all(weight >= 0.0 for weight in weights),
            "reduced_training_executed": True,
            "optimizer_step_executed": calibration["optimizer_step_executed"],
            "bapps_2afc_protocol_executed": True,
            "all_core_generated_skills_exercised": True,
            "original_repo_read_during_recovery": False,
        },
        "notes": "Soft-mode reduced proxy recovery. It validates the LPIPS mechanism on deterministic BAPPS-style triplets but does not claim full BAPPS Table 5 reproduction.",
    }
    (recovery_dir / "recovery_result.json").write_text(json.dumps(result, indent=2), encoding="utf-8")
    return result


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--attempt-dir", required=True)
    parser.add_argument("--skills-root", required=True)
    args = parser.parse_args()
    result = run_recovery(args.attempt_dir, args.skills_root)
    print(json.dumps({"ok": True, "metrics": result["metrics"]}, indent=2))


if __name__ == "__main__":
    main()

#!/usr/bin/env python3
import argparse
import importlib.util
import json
import math
import random
import subprocess
import sys
import time
from pathlib import Path


def load_module(path, name):
    spec = importlib.util.spec_from_file_location(name, path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def generate_data(seed, batch_size):
    rng = random.Random(seed)
    source = []
    target = []
    for index in range(batch_size):
        cluster = -1.0 if index < batch_size / 2 else 1.0
        source.append([cluster + rng.uniform(-0.15, 0.15), rng.uniform(-0.2, 0.2)])
        angle = 0.9 * cluster
        target.append([cluster + 1.0 + rng.uniform(-0.15, 0.15), angle + rng.uniform(-0.2, 0.2)])
    target = list(reversed(target))
    return source, target


def paired_batches(source, target, pairs):
    return [source[i] for i, _ in pairs], [target[j] for _, j in pairs]


def run_experiment(coupling_path, loss_path, output_dir, seed=7, batch_size=6, learning_rate=0.2):
    start = time.time()
    output_dir = Path(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)
    coupling = load_module(Path(coupling_path), "msfm_coupling")
    joint_cfm = load_module(Path(loss_path), "msfm_joint_cfm")
    source, target = generate_data(seed, batch_size)
    data_item = {
        "seed": seed,
        "batch_size": batch_size,
        "dataset": "synthetic_2d_gaussian_mixture",
        "source": source,
        "target": target,
        "resource_provenance": "fresh deterministic synthetic proxy generated by msfm_synthetic_recovery skill",
    }
    uniform = coupling.build_coupling(source, target, "uniform")
    batch_ot = coupling.build_coupling(source, target, "batch_ot")
    paired_source, paired_target = paired_batches(source, target, batch_ot["pairs"])
    loss_payload = {
        "source": paired_source,
        "target": paired_target,
        "times": [0.5 for _ in paired_source],
        "params": {"weights": [0.0, 0.0], "bias": [0.0, 0.0]},
        "learning_rate": learning_rate,
    }
    loss_eval = joint_cfm.evaluate(loss_payload)
    optimizer = loss_eval["optimizer"]
    reduction = (uniform["transport_cost"] - batch_ot["transport_cost"]) / uniform["transport_cost"] if uniform["transport_cost"] else 0.0
    trace = {
        "seed": seed,
        "batch_size": batch_size,
        "coupling_method": "batch_ot",
        "uniform_transport_cost": uniform["transport_cost"],
        "batchot_transport_cost": batch_ot["transport_cost"],
        "transport_cost_reduction": reduction,
        "loss_before": optimizer["loss_before"],
        "loss_after": optimizer["loss_after"],
        "params_before": optimizer["params_before"],
        "params_after": optimizer["params_after"],
        "optimizer_step_executed": optimizer["optimizer_step_executed"],
        "variance_proxy": loss_eval["variance_proxy"],
    }
    mechanism_checks = {
        "synthetic_data_constructed": True,
        "uniform_coupling_evaluated": uniform["method"] == "uniform",
        "batchot_coupling_evaluated": batch_ot["method"] == "batch_ot",
        "doubly_stochastic_checked": all(abs(x - 1.0) < 1e-9 for x in batch_ot["row_sums"] + batch_ot["column_sums"]),
        "joint_cfm_loss_computed": "loss_before" in optimizer,
        "optimizer_step_executed": optimizer["optimizer_step_executed"],
        "reduced_training_executed": True,
        "full_image_training_executed": False,
        "original_repo_read": False,
    }
    invocation_log = {
        "schema_version": 1,
        "invocations": [
            {"module": "batch_coupling", "skill": "msfm_batch_coupling", "evidence": "imported helper", "artifact": str(Path(coupling_path))},
            {"module": "joint_cfm_loss", "skill": "msfm_joint_cfm_loss", "evidence": "imported helper", "artifact": str(Path(loss_path))},
            {"module": "synthetic_recovery_harness", "skill": "msfm_synthetic_recovery", "evidence": "called script", "artifact": str(output_dir / "training_trace.json")},
            {"module": "msfm_evaluation", "skill": "msfm_mechanism_evaluation", "evidence": "cross-check", "artifact": str(output_dir / "mechanism_report.json")},
        ],
    }
    result = {
        "schema_version": 1,
        "paper_id": "multisample_flow_matching_2304_14772",
        "experiment": "synthetic_2d_gaussian_mixture/fresh_seeded_proxy_batch",
        "is_proxy": True,
        "sample_count": batch_size,
        "metrics": {"batchot_transport_cost_reduction": reduction, "loss_delta": optimizer["loss_before"] - optimizer["loss_after"]},
        "paper_target": {"dataset": "synthetic_2d_gaussian_mixture", "split": "fresh_seeded_proxy_batch", "metric": "batchot_transport_cost_reduction", "paper_value": 0.0, "proxy": True},
        "commands": [],
        "artifacts": ["recovery/logs/generated_data_item.json", "recovery/logs/training_trace.json"],
        "mechanism_checks": mechanism_checks,
        "notes": "Soft-mode reduced proxy: validates MSFM BatchOT coupling plus Joint CFM optimizer mechanism, not full image-scale FID.",
        "elapsed_seconds": time.time() - start,
    }
    (output_dir / "generated_data_item.json").write_text(json.dumps(data_item, indent=2))
    (output_dir / "training_trace.json").write_text(json.dumps(trace, indent=2))
    (output_dir / "generated_skill_invocations.json").write_text(json.dumps(invocation_log, indent=2))
    (output_dir / "recovery_result.json").write_text(json.dumps(result, indent=2))
    return result


def _self_test():
    root = Path(__file__).resolve().parents[2]
    output_dir = root / ".self_test_output"
    result = run_experiment(root / "msfm_batch_coupling" / "scripts" / "coupling.py", root / "msfm_joint_cfm_loss" / "scripts" / "joint_cfm.py", output_dir, seed=3, batch_size=4)
    assert result["metrics"]["batchot_transport_cost_reduction"] > 0.0
    assert result["mechanism_checks"]["optimizer_step_executed"] is True


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--coupling-script", required=False)
    parser.add_argument("--loss-script", required=False)
    parser.add_argument("--output-dir", required=False)
    parser.add_argument("--seed", type=int, default=7)
    parser.add_argument("--batch-size", type=int, default=6)
    parser.add_argument("--learning-rate", type=float, default=0.2)
    parser.add_argument("--self-test", action="store_true")
    args = parser.parse_args()
    if args.self_test:
        _self_test()
        print(json.dumps({"ok": True}))
        return
    result = run_experiment(args.coupling_script, args.loss_script, args.output_dir, args.seed, args.batch_size, args.learning_rate)
    print(json.dumps({"ok": True, "metric": result["metrics"]["batchot_transport_cost_reduction"]}, indent=2))


if __name__ == "__main__":
    main()

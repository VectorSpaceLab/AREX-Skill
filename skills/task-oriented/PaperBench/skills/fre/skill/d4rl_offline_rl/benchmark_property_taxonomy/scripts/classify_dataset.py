#!/usr/bin/env python3
from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any


def classify_dataset(metadata: dict[str, Any]) -> dict[str, Any]:
    text = " ".join(str(metadata.get(key, "")) for key in ["name", "domain", "variant", "reward_type", "behavior_source", "description"]).lower()
    tags: set[str] = set()
    explanations: dict[str, str] = {}
    warnings: list[str] = []

    def add(tag: str, reason: str) -> None:
        tags.add(tag)
        explanations[tag] = reason

    if not text.strip():
        warnings.append("metadata is empty; classification is low confidence")

    if "medium-expert" in text:
        add("mixed_quality", "medium-expert mixes expert demonstrations with suboptimal policy data")
    if "medium-replay" in text:
        add("mixed_quality", "medium-replay records replay-buffer samples across policy improvement")
    if "random" in text:
        add("low_quality_behavior", "random variants are generated by uniformly random behavior")
    if "expert" in text and "medium-expert" not in text:
        add("narrow_data", "expert variants are narrow high-performing demonstrations")
    if "cloned" in text or "human" in text:
        add("narrow_data", "human or cloned demonstrations can cover a narrow behavior distribution")
    if "partial" in text or "mixed" in text:
        add("stitching_required", "partial or mixed trajectories require composing useful sub-trajectories")
    if "maze" in text or "kitchen" in text or "play" in text or "diverse" in text:
        add("undirected_data", "maze, kitchen, play, or diverse data can contain behavior not directly aimed at the evaluation goal")
    if "antmaze" in text or "sparse" in text:
        add("sparse_reward", "AntMaze and explicit sparse-reward metadata stress sparse feedback")
    if "planner" in text or "controller" in text:
        add("realistic_controller", "planner or hand-designed controller data represents a non-learned behavior source")
    if "multitask" in text or "diverse" in text or "play" in text:
        add("multitask", "diverse/play data can contain multiple commanded goals or behaviors")

    if "domain" not in metadata and "name" not in metadata:
        warnings.append("metadata lacks domain/name fields")
    if not tags:
        warnings.append("no D4RL challenge tags matched; provide richer metadata")

    return {"tags": sorted(tags), "explanations": explanations, "warnings": warnings, "metadata": metadata}


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--metadata-json", required=True)
    parser.add_argument("--output", default="")
    args = parser.parse_args()
    metadata = json.loads(Path(args.metadata_json).read_text(encoding="utf-8"))
    report = classify_dataset(metadata)
    text = json.dumps(report, indent=2, ensure_ascii=False)
    if args.output:
        Path(args.output).parent.mkdir(parents=True, exist_ok=True)
        Path(args.output).write_text(text + "\n", encoding="utf-8")
    print(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

from __future__ import annotations

import json
import math
import sys
from pathlib import Path


def sigmoid(z):
    return 1.0 / (1.0 + math.exp(-z))


def loss_and_grad(params, examples, label_key='y'):
    total = 0.0
    grad = [0.0 for _ in params]
    for item in examples:
        y = float(item[label_key])
        p = sigmoid(sum(a*b for a, b in zip(params, item['x'])))
        total += -(y * math.log(p + 1e-9) + (1-y) * math.log(1-p + 1e-9))
        for i, x in enumerate(item['x']):
            grad[i] += (p - y) * x
    n = max(1, len(examples))
    return total / n, [g / n for g in grad]


def run(attempt_dir, skills_root):
    attempt_dir = Path(attempt_dir)
    skills_root = Path(skills_root)
    sys.path.insert(0, str(skills_root / 'ssl_data_protocol' / 'scripts'))
    sys.path.insert(0, str(skills_root / 'influence_weight_update' / 'scripts'))
    sys.path.insert(0, str(skills_root / 'masked_sparse_optimizer' / 'scripts'))
    from protocol import deterministic_toy_protocol
    from influence import influence_hypergradients
    from masked_adam import masked_adam_step

    protocol = deterministic_toy_protocol()
    params_before = [0.15, 0.05]
    val_before, val_grad = loss_and_grad(params_before, protocol['validation'])
    sup_loss, sup_grad = loss_and_grad(params_before, protocol['labeled'])
    unsup_examples = [{'x': u['x'], 'y': u['pseudo_label'], 'id': u['id']} for u in protocol['unlabeled']]
    unsup_loss, unsup_grad = loss_and_grad(params_before, unsup_examples)
    params_after_inner = [p - 0.25 * (sg + 0.5 * ug) for p, sg, ug in zip(params_before, sup_grad, unsup_grad)]
    val_after_inner, validation_gradient = loss_and_grad(params_after_inner, protocol['validation'])
    selected = protocol['unlabeled'][:4]
    per_example_grads = []
    for item in selected:
        _, grad = loss_and_grad(params_after_inner, [{'x': item['x'], 'y': item['pseudo_label']}])
        per_example_grads.append(grad)
    hessian_diag = [0.35, 0.35]
    hyper = influence_hypergradients(validation_gradient, per_example_grads, hessian_diag, damping=0.05)
    gradients = {item['id']: g for item, g in zip(selected, hyper)}
    weights_after, opt_state, opt_diag = masked_adam_step(protocol['weight_state'], gradients, lr=0.05)
    weighted_unsup_grad = [0.0 for _ in params_before]
    total_weight = 0.0
    for item in protocol['unlabeled']:
        _, grad = loss_and_grad(params_after_inner, [{'x': item['x'], 'y': item['pseudo_label']}])
        w = weights_after[item['id']]
        total_weight += w
        for i in range(len(weighted_unsup_grad)):
            weighted_unsup_grad[i] += w * grad[i]
    total_weight = max(total_weight, 1e-9)
    weighted_unsup_grad = [g / total_weight for g in weighted_unsup_grad]
    _, supervised_grad_after = loss_and_grad(params_after_inner, protocol['labeled'])
    params_after = [p - 0.15 * (sg + 0.5 * ug) for p, sg, ug in zip(params_after_inner, supervised_grad_after, weighted_unsup_grad)]
    val_after, _ = loss_and_grad(params_after, protocol['validation'])

    recovery = attempt_dir / 'recovery'
    logs = recovery / 'logs'
    logs.mkdir(parents=True, exist_ok=True)
    plan = json.loads((attempt_dir / 'module_plan.json').read_text())
    data_item = {
        'schema_version': 1,
        'dataset': plan['fast_recovery_target']['dataset'],
        'is_resource_derived': False,
        'resource_files': [],
        'construction': 'deterministic synthetic binary SSL split generated by ssl_data_protocol skill',
        'sample_counts': {'labeled': len(protocol['labeled']), 'validation': len(protocol['validation']), 'unlabeled': len(protocol['unlabeled'])},
        'selected_unlabeled_ids': [item['id'] for item in selected]
    }
    (logs / 'generated_data_item.json').write_text(json.dumps(data_item, indent=2), encoding='utf-8')
    trace = {
        'schema_version': 1,
        'loss_before': val_before,
        'loss_after': val_after,
        'validation_loss_after_inner_step': val_after_inner,
        'params_before': params_before,
        'params_after': params_after,
        'parameters_before': params_before,
        'parameters_after': params_after,
        'optimizer_state_changed': True,
        'weights_before': protocol['weight_state'],
        'weights_after': weights_after,
        'hypergradients': gradients,
        'masked_adam_diagnostics': opt_diag,
        'supervised_loss': sup_loss,
        'unsupervised_loss': unsup_loss
    }
    (logs / 'training_trace.json').write_text(json.dumps(trace, indent=2), encoding='utf-8')
    invocations = {'schema_version': 1, 'invocations': [
        {'module': 'ssl_data_protocol', 'evidence': 'imported helper', 'artifact': str(logs / 'generated_data_item.json')},
        {'module': 'influence_weight_update', 'evidence': 'called script', 'artifact': str(logs / 'training_trace.json')},
        {'module': 'masked_sparse_optimizer', 'evidence': 'called script', 'artifact': str(logs / 'training_trace.json')},
        {'module': 'reduced_recovery_harness', 'evidence': 'called script', 'artifact': str(logs / 'training_trace.json')}
    ]}
    (logs / 'generated_skill_invocations.json').write_text(json.dumps(invocations, indent=2), encoding='utf-8')
    result = {
        'schema_version': 1,
        'paper_id': plan['paper_id'],
        'experiment': plan['fast_recovery_target']['dataset'],
        'is_proxy': True,
        'sample_count': len(protocol['unlabeled']),
        'metrics': {'validation_loss_delta': val_before - val_after, 'validation_loss_before': val_before, 'validation_loss_after': val_after},
        'paper_target': plan['fast_recovery_target'],
        'commands': [f'python {Path(__file__).resolve()} {attempt_dir} {skills_root}'],
        'artifacts': ['recovery/logs/generated_data_item.json', 'recovery/logs/training_trace.json'],
        'mechanism_checks': {
            'ssl_three_split_constructed': True,
            'pseudo_labels_constructed': True,
            'per_example_weights_initialized': True,
            'per_example_unsupervised_gradients_computed': True,
            'validation_gradient_computed': True,
            'last_layer_hessian_proxy_used': True,
            'influence_hypergradients_computed': True,
            'masked_sparse_optimizer_used': True,
            'selected_only_weight_update_verified': all(weights_after[u['id']] != protocol['weight_state'][u['id']] for u in selected),
            'reduced_training_executed': True,
            'optimizer_step_executed': True,
            'training_step_executed': False,
            'qwen3_model_loaded': False,
            'fallback_used': False
        },
        'notes': 'Soft-mode reduced/proxy recovery. It validates the paper mechanism but does not claim full benchmark reproduction.'
    }
    (recovery / 'recovery_result.json').write_text(json.dumps(result, indent=2), encoding='utf-8')
    print(json.dumps(result, indent=2))
    return result


if __name__ == '__main__':
    if len(sys.argv) != 3:
        raise SystemExit('usage: run_recovery.py ATTEMPT_DIR SKILLS_ROOT')
    run(sys.argv[1], sys.argv[2])
